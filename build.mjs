// HEXBUSTER Z build script — zero dependencies, just Node 18+.
//   node build.mjs          -> dist/index.html (single self-contained file)
//   node build.mjs --watch  -> rebuild on every change
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8');
const list = (dir, ext) => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith(ext)).sort();

export function build() {
  const pkg = JSON.parse(read('package.json'));
  // data/*.json -> one DATA object (validated here, so a typo fails the build, not the game)
  const DATA = {};
  for (const f of list('data', '.json')) {
    try { DATA[f.replace(/\.json$/, '')] = JSON.parse(read('data', f)); }
    catch (e) { throw new Error(`data/${f} is not valid JSON: ${e.message}`); }
  }
  let commit = process.env.GITHUB_SHA ? process.env.GITHUB_SHA.slice(0, 7) : ''; if (!commit) { try { commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { commit = 'dev'; } }
  const info = { version: pkg.version, commit, saveSchema: DATA.meta ? DATA.meta.saveSchema : 1, built: new Date().toISOString() };
  const banner = `// ---- generated by build.mjs ----\nconst DATA = ${JSON.stringify(DATA)};\nconst BUILD_INFO = ${JSON.stringify(info)};\n`;
  const js = banner + list('src/js', '.js').map(f => read('src/js', f)).join('\n');
  const css = list('src/css', '.css').map(f => read('src/css', f)).join('\n');
  const html = read('src/index.template.html').replace('/*CSS*/', () => css).replace('/*GAME*/', () => js);
  fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(root, 'dist', 'index.html'), html);
  return { bytes: html.length, version: pkg.version };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const run = () => { try { const r = build(); console.log(`built dist/index.html  v${r.version}  ${(r.bytes / 1024).toFixed(1)} KB`); } catch (e) { console.error('BUILD FAILED:', e.message); process.exitCode = 1; } };
  run();
  if (process.argv.includes('--watch')) {
    let t; const again = () => { clearTimeout(t); t = setTimeout(run, 120); };
    for (const d of ['src', 'src/js', 'src/css', 'data']) fs.watch(path.join(root, d), again);
    console.log('watching src/ and data/ …');
  }
}
